// BCM2835 PL011 UART
#define SERIAL_BASE 0x86001000
#define SERIAL_FLAG_REGISTER 0x18
#define SERIAL_CONTROL_REGISTER 0x30
#define SERIAL_INTERRUPT_MASK_REGISTER 0x38
#define SERIAL_INTERRUPT_CLEAR_REGISTER 0x44
#define SERIAL_BUFFER_FULL (1 << 5)
#define SERIAL_RECEIVE_EMPTY (1 << 4)
#define SERIAL_RECEIVE_INTERRUPTS ((1 << 4) | (1 << 6)) // receive and receive timeout

#define PIC_BASE 0x9000B200
#define LOCAL_PIC_BASE 0x90100000
#define SYSTEM_TIMER_BASE 0x90003000
